import { readFile, writeFile } from 'node:fs/promises'
import ts from 'typescript'

const specUrl = new URL('../docs/openapi/v3.json', import.meta.url)
const declarationsUrl = new URL('../resources/js/generated/generated.d.ts', import.meta.url)
const outputUrl = new URL('../resources/js/generated/openapi-enums.ts', import.meta.url)
const spec = JSON.parse(await readFile(specUrl, 'utf8'))
const schemas = spec.components?.schemas ?? {}
const enumSchemas = new Map(Object.entries(schemas).filter(([, schema]) => {
    return schema?.type === 'string' && Array.isArray(schema.enum)
}))

const declarations = await readFile(declarationsUrl, 'utf8')
const sourceFile = ts.createSourceFile(declarationsUrl.pathname, declarations, ts.ScriptTarget.Latest, true)

function addStringUnionTypes(node) {
    if (ts.isTypeAliasDeclaration(node) && ts.isUnionTypeNode(node.type)) {
        const values = node.type.types.map((type) => {
            if (!ts.isLiteralTypeNode(type) || !ts.isStringLiteral(type.literal)) {
                return null
            }

            return type.literal.text
        })

        const memberNames = values.map((value) => value?.replace(/_([a-z0-9])/g, (_, character) => character.toUpperCase()))
        const areValidMemberNames = memberNames.every((name) => name && /^[A-Za-z_$][\w$]*$/.test(name))

        if (values.every((value) => value !== null) && areValidMemberNames && new Set(memberNames).size === memberNames.length && !enumSchemas.has(node.name.text)) {
            enumSchemas.set(node.name.text, { type: 'string', enum: values })
        }
    }

    ts.forEachChild(node, addStringUnionTypes)
}

addStringUnionTypes(sourceFile)

if (enumSchemas.size === 0) {
    throw new Error('No named string enums found in the OpenAPI components.')
}

const generatedDeclarations = [...enumSchemas].map(([name, schema]) => {
    if (!/^[A-Za-z_$][\w$]*$/.test(name)) {
        throw new Error(`OpenAPI enum schema name is not a valid TypeScript identifier: ${name}`)
    }

    if (!schema.enum.every((value) => typeof value === 'string')) {
        throw new Error(`OpenAPI enum schema contains a non-string value: ${name}`)
    }

    const enumNames = schema['x-enumNames']

    if (enumNames !== undefined && (!Array.isArray(enumNames) || enumNames.length !== schema.enum.length || !enumNames.every((name) => typeof name === 'string'))) {
        throw new Error(`OpenAPI enum schema has invalid case names: ${name}`)
    }

    const memberNames = schema.enum.map((value, index) => {
        const caseName = enumNames?.[index]
        return caseName
            ? caseName.toLowerCase().replace(/_([a-z0-9])/g, (_, character) => character.toUpperCase())
            : value.replace(/_([a-z0-9])/g, (_, character) => character.toUpperCase())
    })

    if (!memberNames.every((memberName) => /^[A-Za-z_$][\w$]*$/.test(memberName))) {
        throw new Error(`OpenAPI enum schema contains a case name that is not a valid TypeScript identifier: ${name}`)
    }

    if (new Set(memberNames).size !== memberNames.length) {
        throw new Error(`OpenAPI enum schema contains duplicate case names: ${name}`)
    }

    const values = schema.enum
        .map((value, index) => `    ${JSON.stringify(memberNames[index])}: ${JSON.stringify(value)},`)
        .join('\n')

    return `export const ${name} = {\n${values}\n} as const`
})

const output = [
    '// This file is auto-generated by scripts/generate-openapi-enums.mjs. Do not edit directly.',
    '',
    ...generatedDeclarations.flatMap((declaration) => [declaration, '']),
].join('\n')

await writeFile(outputUrl, output)
